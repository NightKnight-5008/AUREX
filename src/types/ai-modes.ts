/**
 * AUREX FINANCIAL OPERATING SYSTEM - AI MODES
 *
 * Separates different types of AI-assisted analysis with clear boundaries.
 *
 * PHILOSOPHY:
 * - ANALYST MODE: Deterministic ledger queries, no AI/LLM
 * - FORECAST MODE: Statistical time-series analysis, no LLM
 * - EXPLAINER MODE: LLM-generated narratives with clear disclaimers
 *
 * GUARANTEES:
 * - Analyst Mode: 100% deterministic, source data always available
 * - Forecast Mode: Statistical only, assumptions clearly stated
 * - Explainer Mode: Clearly marked as AI-generated, reviewable
 *
 * USER TRANSPARENCY:
 * - Every insight tagged with its mode
 * - Source data always linked
 * - Disclaimers on AI-generated content
 * - User can drill down to raw data
 */

/**
 * AI Mode enumeration
 */
export enum AIMode {
  /** Deterministic ledger-based analysis (no AI) */
  ANALYST = 'ANALYST',

  /** Statistical forecasting (no LLM) */
  FORECAST = 'FORECAST',

  /** LLM-generated narrative explanations */
  EXPLAINER = 'EXPLAINER'
}

/**
 * Data source types
 */
export enum DataSource {
  /** Raw ledger entries */
  LEDGER = 'LEDGER',

  /** Statistical computation */
  STATISTICAL = 'STATISTICAL',

  /** Large Language Model */
  LLM = 'LLM',

  /** User input */
  USER = 'USER',

  /** External API */
  EXTERNAL_API = 'EXTERNAL_API'
}

/**
 * Base insight interface
 */
export interface BaseInsight {
  /** Unique insight ID */
  id: string;

  /** AI mode that generated this insight */
  mode: AIMode;

  /** Data source */
  source: DataSource;

  /** When generated */
  timestamp: Date;

  /** Generated by (user ID or 'system') */
  generatedBy: string;

  /** Whether this insight has been reviewed */
  reviewed: boolean;

  /** Review notes */
  reviewNotes?: string;
}

/**
 * Analyst Mode Insight (100% deterministic)
 */
export interface AnalystInsight extends BaseInsight {
  mode: AIMode.ANALYST;
  source: DataSource.LEDGER;

  /** Analysis type */
  analysisType:
    | 'BALANCE'
    | 'EXPENSE_BREAKDOWN'
    | 'REVENUE_BREAKDOWN'
    | 'CASH_FLOW'
    | 'TREND'
    | 'COMPARISON';

  /** Title of the insight */
  title: string;

  /** Description */
  description: string;

  /** Numerical results */
  metrics: {
    /** Primary metric value */
    value: number;

    /** Metric label */
    label: string;

    /** Currency (if applicable) */
    currency?: string;

    /** Comparison value (if applicable) */
    comparisonValue?: number;

    /** Comparison period (if applicable) */
    comparisonPeriod?: string;

    /** Percentage change (if applicable) */
    percentageChange?: number;
  }[];

  /** Ledger entry IDs used in this analysis */
  ledgerEntryIds: string[];

  /** Account IDs involved */
  accountIds: string[];

  /** Time period */
  period?: {
    start: Date;
    end: Date;
  };

  /** Raw data used for calculation */
  sourceData: Record<string, unknown>;

  /** Calculation method (for transparency) */
  calculationMethod: string;
}

/**
 * Forecast Mode Insight (statistical only)
 */
export interface ForecastInsight extends BaseInsight {
  mode: AIMode.FORECAST;
  source: DataSource.STATISTICAL;

  /** Forecast type */
  forecastType: 'LINEAR_TREND' | 'MOVING_AVERAGE' | 'SEASONAL' | 'EXPONENTIAL_SMOOTHING';

  /** Title */
  title: string;

  /** Description */
  description: string;

  /** Forecast values */
  predictions: Array<{
    /** Period (e.g., "2024-03", "Q1 2024") */
    period: string;

    /** Predicted value */
    value: number;

    /** Lower confidence bound */
    lowerBound: number;

    /** Upper confidence bound */
    upperBound: number;

    /** Confidence level (e.g., 0.95 for 95%) */
    confidence: number;
  }>;

  /** Historical data used */
  historicalData: Array<{
    period: string;
    value: number;
  }>;

  /** Statistical assumptions */
  assumptions: string[];

  /** Model parameters */
  modelParameters: Record<string, number>;

  /** Goodness of fit metrics */
  fitMetrics: {
    /** R-squared */
    rSquared?: number;

    /** Mean absolute error */
    mae?: number;

    /** Root mean squared error */
    rmse?: number;
  };

  /** Warnings about data quality */
  warnings: string[];
}

/**
 * Explainer Mode Insight (LLM-generated)
 */
export interface ExplainerInsight extends BaseInsight {
  mode: AIMode.EXPLAINER;
  source: DataSource.LLM;

  /** Explanation type */
  explanationType: 'SUMMARY' | 'COMPARISON' | 'TREND_EXPLANATION' | 'RECOMMENDATION';

  /** Title */
  title: string;

  /** LLM-generated narrative */
  narrative: string;

  /** Source metrics used to generate narrative */
  sourceMetrics: {
    /** Analyst insights referenced */
    analystInsights?: AnalystInsight[];

    /** Forecast insights referenced */
    forecastInsights?: ForecastInsight[];

    /** Raw data referenced */
    rawData?: Record<string, unknown>;
  };

  /** LLM model used */
  llmModel: string;

  /** LLM temperature setting */
  temperature: number;

  /** Prompt used (for transparency) */
  prompt?: string;

  /** Disclaimer text */
  disclaimer: string;

  /** Confidence score (0-1) */
  confidenceScore?: number;

  /** Whether this was human-edited */
  humanEdited: boolean;

  /** Edit history */
  editHistory?: Array<{
    timestamp: Date;
    editedBy: string;
    changes: string;
  }>;
}

/**
 * Insight collection
 */
export interface InsightCollection {
  /** Collection ID */
  id: string;

  /** Collection name */
  name: string;

  /** Description */
  description: string;

  /** Insights in this collection */
  insights: Array<AnalystInsight | ForecastInsight | ExplainerInsight>;

  /** Created timestamp */
  createdAt: Date;

  /** Last updated */
  updatedAt: Date;

  /** Created by */
  createdBy: string;
}

/**
 * AI Mode configuration
 */
export interface AIModeConfig {
  /** Which modes are enabled */
  enabledModes: Set<AIMode>;

  /** Analyst mode settings */
  analyst: {
    /** Default time period for analysis */
    defaultPeriodDays: number;

    /** Minimum entries required for trend analysis */
    minEntriesForTrend: number;
  };

  /** Forecast mode settings */
  forecast: {
    /** Default forecast periods */
    defaultForecastPeriods: number;

    /** Confidence level (e.g., 0.95 for 95%) */
    confidenceLevel: number;

    /** Minimum historical data points */
    minHistoricalPoints: number;
  };

  /** Explainer mode settings */
  explainer: {
    /** LLM model to use */
    llmModel: string;

    /** Temperature (0.0 - 1.0) */
    temperature: number;

    /** Max tokens */
    maxTokens: number;

    /** Whether to show prompts to users */
    showPrompts: boolean;

    /** Require human review before showing */
    requireReview: boolean;
  };
}

