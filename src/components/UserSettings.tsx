import { useState } from 'react';
import { useAuth } from '@/contexts/auth-context';
import { useWorkspace } from '@/hooks/use-workspace';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs';
import { Badge } from '@/components/ui/badge';
import { Alert, AlertDescription } from '@/components/ui/alert';
import { Shield, Settings as SettingsIcon, Lock, AlertTriangle, ShoppingBag, Info } from 'lucide-react';
import { SecuritySettings } from '@/components/SecuritySettings';
import { GeneralSettings } from '@/components/GeneralSettings';
import { ShopifySettings } from '@/components/ShopifySettings';
import { SecurityDataIntegrityInfo } from '@/components/SecurityDataIntegrityInfo';
import {
  AlertDialog,
  AlertDialogAction,
  AlertDialogCancel,
  AlertDialogContent,
  AlertDialogDescription,
  AlertDialogFooter,
  AlertDialogHeader,
  AlertDialogTitle,
} from '@/components/ui/alert-dialog';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { Button } from '@/components/ui/button';

interface UserSettingsProps {
  countryCode: string;
  onCountryChange: (countryCode: string) => void;
  locale?: string;
  onLocaleChange: (locale: string | undefined) => void;
  currency?: string;
  onCurrencyChange?: (currency: string) => void;
}

export function UserSettings({
  countryCode,
  onCountryChange,
  locale,
  onLocaleChange,
  currency,
  onCurrencyChange,
}: UserSettingsProps) {
  const { user } = useAuth();
  const workspaceState = useWorkspace();
  const [showSecurityDialog, setShowSecurityDialog] = useState(false);
  const [securityPassword, setSecurityPassword] = useState('');
  const [isSecurityUnlocked, setIsSecurityUnlocked] = useState(false);
  const [selectedTab, setSelectedTab] = useState('general');

  if (!user) return null;

  const handleSecurityTabClick = () => {
    // Check if security is already unlocked
    const unlocked = sessionStorage.getItem(`security-unlocked-${user.id}`);
    if (unlocked === 'true') {
      setIsSecurityUnlocked(true);
      setSelectedTab('security');
    } else {
      setShowSecurityDialog(true);
    }
  };

  const handleSecurityUnlock = () => {
    // In production, this should verify against the stored security password
    // For now, we'll check against a simple pattern
    const storedPassword = localStorage.getItem(`security-password-${user.id}`);

    if (storedPassword) {
      const passwordConfig = JSON.parse(storedPassword);
      if (securityPassword === passwordConfig.password) {
        setIsSecurityUnlocked(true);
        sessionStorage.setItem(`security-unlocked-${user.id}`, 'true');
        setShowSecurityDialog(false);
        setSecurityPassword('');
        setSelectedTab('security');

        // Log security access
        console.log(`[SECURITY LOG] Security tab accessed at ${new Date().toISOString()}`);
      } else {
        alert('❌ Invalid security password. Access denied.');
        setSecurityPassword('');
      }
    } else {
      // First time setup - allow access without password
      // Security password will be auto-generated by SecuritySettings component
      setIsSecurityUnlocked(true);
      sessionStorage.setItem(`security-unlocked-${user.id}`, 'true');
      setShowSecurityDialog(false);
      setSecurityPassword('');
      setSelectedTab('security');

      // Log first-time security setup
      console.log(`[SECURITY LOG] First-time security setup initiated at ${new Date().toISOString()}`);
    }
  };

  const handleTabChange = (value: string) => {
    if (value === 'security') {
      handleSecurityTabClick();
    } else {
      setSelectedTab(value);
    }
  };

  return (
    <div className="space-y-6">
      {/* Settings Header */}
      <Card>
        <CardHeader>
          <div className="flex items-center justify-between">
            <div>
              <CardTitle className="flex items-center gap-2">
                <SettingsIcon className="w-5 h-5" />
                Settings
              </CardTitle>
              <CardDescription>
                Manage your account, security, and application preferences
              </CardDescription>
            </div>
            <Badge variant="outline">User: {user.email}</Badge>
          </div>
        </CardHeader>
      </Card>

      {/* Settings Tabs */}
      <Tabs value={selectedTab} onValueChange={handleTabChange} className="w-full">
        <TabsList className="grid w-full grid-cols-4 max-w-6xl">
          <TabsTrigger value="general" className="flex items-center gap-2">
            <SettingsIcon className="w-4 h-4" />
            General
          </TabsTrigger>
          <TabsTrigger value="integrations" className="flex items-center gap-2">
            <ShoppingBag className="w-4 h-4" />
            Integrations
          </TabsTrigger>
          <TabsTrigger value="security" className="flex items-center gap-2">
            <Shield className="w-4 h-4" />
            Security
            {isSecurityUnlocked && (
              <Lock className="w-3 h-3 text-green-600" />
            )}
          </TabsTrigger>
          <TabsTrigger value="about" className="flex items-center gap-2">
            <Info className="w-4 h-4" />
            About
          </TabsTrigger>
        </TabsList>

        <TabsContent value="general" className="mt-6">
          <GeneralSettings
            countryCode={countryCode}
            onCountryChange={onCountryChange}
            locale={locale}
            onLocaleChange={onLocaleChange}
            currency={currency}
            onCurrencyChange={onCurrencyChange}
          />
        </TabsContent>

        <TabsContent value="integrations" className="mt-6">
          <ShopifySettings countryCode={countryCode} />
        </TabsContent>

        <TabsContent value="security" className="mt-6">
          {isSecurityUnlocked ? (
            <SecuritySettings userId={user.id} />
          ) : (
            <Card>
              <CardContent className="flex items-center justify-center p-12">
                <div className="text-center space-y-4">
                  <Lock className="w-16 h-16 mx-auto text-muted-foreground" />
                  <h3 className="text-lg font-semibold">Security Tab Locked</h3>
                  <p className="text-sm text-muted-foreground max-w-md">
                    Please click the Security tab to authenticate with your security password.
                  </p>
                </div>
              </CardContent>
            </Card>
          )}
        </TabsContent>

        <TabsContent value="about" className="mt-6">
          <SecurityDataIntegrityInfo />
        </TabsContent>
      </Tabs>

      {/* Security Authentication Dialog */}
      <AlertDialog open={showSecurityDialog} onOpenChange={setShowSecurityDialog}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle className="flex items-center gap-2">
              <Shield className="w-5 h-5" />
              Security Authentication Required
            </AlertDialogTitle>
            <AlertDialogDescription asChild>
              <div className="space-y-4 text-sm text-muted-foreground">
                <Alert variant="default" className="border-amber-500 dark:border-amber-600">
                  <AlertTriangle className="h-4 w-4 text-amber-600" />
                  <AlertDescription className="text-amber-800 dark:text-amber-200">
                    <strong>Security Notice:</strong> The Security tab contains your 24-character security key
                    and Android app download. Access requires authentication.
                  </AlertDescription>
                </Alert>

                {(() => {
                  const storedPassword = localStorage.getItem(`security-password-${user?.id}`);
                  const isFirstTime = !storedPassword;

                  return (
                    <div className="space-y-2">
                      {isFirstTime ? (
                        <div className="space-y-3 p-4 bg-green-50 dark:bg-green-950 border border-green-200 dark:border-green-800 rounded-lg">
                          <h4 className="font-semibold text-green-900 dark:text-green-100 flex items-center gap-2">
                            <Shield className="w-4 h-4" />
                            First-Time Setup
                          </h4>
                          <p className="text-sm text-green-800 dark:text-green-200">
                            This is your first time accessing the Security tab. Click "Initialize Security" below to:
                          </p>
                          <ul className="text-sm text-green-800 dark:text-green-200 list-disc list-inside space-y-1">
                            <li>Generate your 24-character security key</li>
                            <li>Enable Android app download</li>
                            <li>Set up secure credential management</li>
                          </ul>
                          <p className="text-xs text-green-700 dark:text-green-300 font-medium">
                            No password required for initial setup.
                          </p>
                        </div>
                      ) : (
                        <>
                          <Label htmlFor="auth-security-password">
                            Enter Security Key (24 characters)
                          </Label>
                          <Input
                            id="auth-security-password"
                            type="password"
                            placeholder="Enter your 24-character security key"
                            value={securityPassword}
                            onChange={(e) => setSecurityPassword(e.target.value)}
                            onKeyDown={(e) => {
                              if (e.key === 'Enter') {
                                handleSecurityUnlock();
                              }
                            }}
                            className="font-mono"
                            autoFocus
                          />
                          <p className="text-xs text-muted-foreground">
                            Enter the 24-character security key that was generated when you first accessed this tab.
                          </p>
                        </>
                      )}
                    </div>
                  );
                })()}
              </div>
            </AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel onClick={() => {
              setSecurityPassword('');
              setSelectedTab('general');
            }}>
              Cancel
            </AlertDialogCancel>
            <AlertDialogAction onClick={handleSecurityUnlock}>
              <Shield className="w-4 h-4 mr-2" />
              {(() => {
                const storedPassword = localStorage.getItem(`security-password-${user?.id}`);
                return !storedPassword ? 'Initialize Security' : 'Unlock Security Tab';
              })()}
            </AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>
    </div>
  );
}
