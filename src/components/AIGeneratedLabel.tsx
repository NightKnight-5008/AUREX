/**
 * AI-Generated Label Component
 *
 * Displays when Explainer Mode outputs text
 * Shows: "AI-generated explanation"
 * Tooltip: "Based on your financial data. Always review before acting."
 *
 * ONLY shown for Explainer Mode - NOT for Analyst or Forecast modes
 */

import { Badge } from '@/components/ui/badge';
import { Tooltip, TooltipContent, TooltipProvider, TooltipTrigger } from '@/components/ui/tooltip';
import { Sparkles } from 'lucide-react';

interface AIGeneratedLabelProps {
  /**
   * Type of AI mode
   * Only shows label for 'explainer' mode
   */
  mode?: 'analyst' | 'forecast' | 'explainer';

  /**
   * Optional custom className
   */
  className?: string;
}

export function AIGeneratedLabel({ mode = 'explainer', className }: AIGeneratedLabelProps) {
  // Only show for Explainer mode (deterministic modes don't need labels)
  if (mode !== 'explainer') {
    return null;
  }

  return (
    <TooltipProvider>
      <Tooltip>
        <TooltipTrigger asChild>
          <Badge variant="outline" className={`flex items-center gap-1.5 cursor-help ${className || ''}`}>
            <Sparkles className="h-3 w-3" />
            <span>AI-generated explanation</span>
          </Badge>
        </TooltipTrigger>
        <TooltipContent className="max-w-xs">
          <p className="text-sm">
            Based on your financial data. Always review before acting.
          </p>
        </TooltipContent>
      </Tooltip>
    </TooltipProvider>
  );
}

/**
 * Inline AI-generated label for use in text content
 */
export function InlineAILabel() {
  return (
    <TooltipProvider>
      <Tooltip>
        <TooltipTrigger asChild>
          <span className="inline-flex items-center gap-1 text-xs text-muted-foreground cursor-help">
            <Sparkles className="h-3 w-3" />
            <span className="underline decoration-dotted">AI-generated</span>
          </span>
        </TooltipTrigger>
        <TooltipContent className="max-w-xs">
          <p className="text-sm">
            This explanation was generated by AI based on your financial data. Always review before acting.
          </p>
        </TooltipContent>
      </Tooltip>
    </TooltipProvider>
  );
}
