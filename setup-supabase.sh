#!/bin/bash

# AUREX Supabase Database Setup Script for Mac/Linux

echo "========================================"
echo "AUREX Supabase Database Setup"
echo "========================================"
echo ""

# Check if backend/.env exists
if [ -f "backend/.env" ]; then
    echo "⚠️  backend/.env already exists!"
    echo ""
    read -p "Do you want to overwrite it? (y/n): " OVERWRITE
    if [ "$OVERWRITE" != "y" ]; then
        echo "Setup cancelled."
        exit 0
    fi
fi

echo ""
echo "📝 Please provide your Supabase details:"
echo ""
echo "1. Go to https://supabase.com"
echo "2. Create a new project (if you haven't)"
echo "3. Go to Settings -> Database"
echo "4. Copy the Connection String (URI format)"
echo ""

read -p "Enter your Supabase DATABASE_URL: " DATABASE_URL

if [ -z "$DATABASE_URL" ]; then
    echo "❌ DATABASE_URL cannot be empty!"
    exit 1
fi

echo ""
echo "🔐 Generating secure secrets..."

# Generate random JWT secret
JWT_SECRET=$(openssl rand -hex 32)

# Generate random encryption key (32 chars)
ENCRYPTION_KEY=$(openssl rand -hex 16)

echo ""
echo "📄 Creating backend/.env file..."

cat > backend/.env << EOF
# AUREX Backend Environment Variables
# Generated by setup-supabase.sh

# Database
DATABASE_URL=$DATABASE_URL

# JWT Secret
JWT_SECRET=$JWT_SECRET

# Server
PORT=3001
NODE_ENV=development

# Frontend URL
FRONTEND_URL=http://localhost:3000

# Encryption Key
ENCRYPTION_KEY=$ENCRYPTION_KEY
EOF

echo "✅ backend/.env created successfully!"
echo ""

# Check if .env.local exists
if [ ! -f ".env.local" ]; then
    echo "📄 Creating .env.local file..."
    cat > .env.local << EOF
# AUREX Frontend Environment Variables

# Backend API URL
VITE_API_URL=http://localhost:3001

# Environment
VITE_ENV=development
EOF
    echo "✅ .env.local created successfully!"
    echo ""
fi

echo ""
echo "🚀 Starting backend server to initialize database..."
echo ""

cd backend
npm start &
BACKEND_PID=$!

# Wait a bit for server to start
sleep 5

echo ""
echo "========================================"
echo "Setup Complete!"
echo "========================================"
echo ""
echo "✅ Database configured"
echo "✅ Backend environment ready"
echo "✅ Tables will be created automatically"
echo ""
echo "📍 Backend running on http://localhost:3001"
echo "📍 Test health: curl http://localhost:3001/health"
echo ""
echo "Press Ctrl+C to stop the backend server"
echo "Then run: npm run dev (to start frontend)"
echo ""

# Wait for user to stop
wait $BACKEND_PID
